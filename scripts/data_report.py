"""Write docs/data-quality-report.md from the issues found in data/raw.

Usage: uv run python scripts/data_report.py [--today YYYY-MM-DD]
"""

import argparse
from datetime import date, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from emporio_agent.data import ISSUE_KINDS, DataIssue, StoreData, find_issues, load_store

REPORT = Path(__file__).resolve().parents[1] / "docs" / "data-quality-report.md"


def label(issue: DataIssue, store: StoreData) -> str:
    if issue.entity == "product":
        (pid,) = issue.ids
        return f"Product {pid} ({store.products[pid].name})"
    plural = "s" if len(issue.ids) > 1 else ""
    return f"{issue.entity.capitalize()}{plural} {', '.join(map(str, issue.ids))}"


def render(store: StoreData, issues: list[DataIssue], today: date) -> str:
    counts = {
        "categories.csv": len(store.categories),
        "products.csv": len(store.products),
        "promotions.csv": len(store.promotions),
        "customers.csv": len(store.customers),
        "orders.csv": len(store.orders),
        "order_items.csv": len(store.order_items),
    }
    by_kind = {kind: [i for i in issues if i.kind == kind] for kind in ISSUE_KINDS}
    found = {kind: rows for kind, rows in by_kind.items() if rows}

    lines = [
        "# Data quality report",
        "",
        f"Generated by `scripts/data_report.py` on {today.isoformat()} from `data/raw/*.csv`. "
        "Do not edit by hand: change the checks in `src/emporio_agent/data.py` and rerun the "
        "script.",
        "",
        "The loader validates every row against a typed schema and checks every reference "
        "between files; all rows pass. The findings below are rows that are valid but "
        "inconsistent. None of them is corrected in the data: each kind has a handling rule "
        "that the agent follows.",
        "",
        "## Rows loaded",
        "",
        "| File | Rows |",
        "|---|---|",
        *(f"| `{name}` | {count} |" for name, count in counts.items()),
        "",
        "## Findings",
        "",
        "| Finding | Rows | Handling |",
        "|---|---|---|",
        *(
            f"| {ISSUE_KINDS[kind][0]} | {len(rows)} | {ISSUE_KINDS[kind][1]} |"
            for kind, rows in found.items()
        ),
    ]
    for kind, rows in found.items():
        title, _ = ISSUE_KINDS[kind]
        lines += ["", f"### {title}", ""]
        lines += [f"- {label(issue, store)}: {issue.detail}" for issue in rows]

    lines += [
        "",
        "## Notes",
        "",
        "- Contradictory descriptions are found with a heuristic: the description names "
        "another brand from the catalog, or a different number of strings (`cordas`) or keys "
        "(`teclas`) than the specs. Model-line mismatches without a brand name (for example "
        "a bass named Ibanez described as a Precision) are not detected.",
        f"- Overdue orders depend on the report date: an order still pending or confirmed "
        f"more than 30 days after it was placed, or shipped past its estimated delivery, as "
        f"of {today.isoformat()}.",
        "- Return windows count from receipt, which the data does not record. The agent uses "
        "`estimated_delivery` as the receipt date and treats every order as an online purchase; "
        "the final return decision always goes through a ticket.",
        "- The store manual's own contradictions (two WhatsApp numbers, an accented e-mail "
        "domain, an ambiguous minimum installment) and how the extraction corrects them are "
        "listed in `data/processed/policies/README.md`.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--today", type=date.fromisoformat, help="report date (YYYY-MM-DD)")
    args = parser.parse_args()
    today = args.today or datetime.now(ZoneInfo("America/Campo_Grande")).date()

    store = load_store()
    report = render(store, find_issues(store, today), today)
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
